def judge(title):
    for name, pat in NG:
        if re.search(pat, title):
            return "止める", f"KC無しの購買代行が許されない品目（{name}）"
    if re.search(KAMIOKA_NG, title, re.I):
        return "止める", "韓国で出せない・送れない品（国旗や軍艦＝一発停止の恐れ・医療機器・除菌・電池単体・可燃物）"
    if re.search(COUPANG_BRAND, title, re.I):
        return "止める", "クーパンではハイブランドを出さない（知財の警告が来やすい・3回で1ヶ月停止）"
    if re.search(COUPANG_NG, title):
        return "止める", "クーパンの購買代行で売れない品（公式の판매 불가 품목）"
    if re.search(TSUKAN, title):
        return "止める", "韓国の通関で止まる品（サプリ・医薬品・ペットフード・HANIRO の一覧）"
    if re.search(HAISO, title):
        return "止める", "割れる・溶ける・冷蔵（船便で届くまで日数がかかる）"
    if re.search(KODOMO, title):
        return "止める", "子ども用品（韓国の事業者しか認証を取れない）"
    if re.search(SDS, title):
        return "確かめる", "航空便で送れないことがある品（イヤホンの充電ケース＝補助電池扱い・スピーカー＝磁石・インク類＝SDS）→ HANIRO に可否を確かめてから"
    if re.search(DENKI, title):
        return "確かめる", "電気製品（韓国は220V・品目表で可否を確かめ、説明に変圧器を明記）"
    return "通す", ""


def selftest():
    cases = [
        ("Anker USB急速充電器 20W スマホ 充電器", "止める"),
        ("パナソニック LED電球 E26 60形", "止める"),
        ("アイリスオーヤマ 超音波洗浄機", "止める"),
        ("ベビー 用 スプーン セット", "止める"),
        ("タミヤ 1/700 戦艦 大和", "止める"),
        ("オムロン 上腕式血圧計 HCR-7106", "止める"),
        ("パイロット 万年筆 カスタム742", "確かめる"),
        ("GUCCI ベルト レザー", "止める"),
        ("東京マルイ 電動ガン M4A1", "止める"),
        ("Kindle Paperwhite 16GB", "止める"),
        ("タイガー 炊飯器 5.5合 IH", "確かめる"),
        ("シマノ スピニングリール 23 セドナ", "通す"),
        ("シマノ リール ストラディック C3000", "通す"),
        ("ロイズ 生チョコレート 20粒", "止める"),
        ("ザバス ホエイプロテイン100 1kg", "止める"),
        ("グリニーズ 犬用 トリーツ", "止める"),
        ("ウタマロ 洗濯 石けん 133g", "止める"),
        ("ヘンケルス 包丁 三徳 18cm", "止める"),
    ]
    bad = 0
    for t, want in cases:
        got, why = judge(t)
        bad += got != want
        print("✅" if got == want else "🔴", t, "→", got, why)
    print("不一致", bad, "件")
    return bad


if __name__ == "__main__":
    sys.exit(1 if selftest() else 0)
